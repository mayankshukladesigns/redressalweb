// ─── SLA / overdue derivation ──────────────────────────────────────────────
// A pending ticket's overdue state is derived from its submission date using
// the same rules as the ticket-details timeline (see TicketDetailsScreen):
//   • Reminder sent at 7 days, Escalated to DPO (view only) at 14 days — timeline only
//   • OVERDUE only at 21 days from creation — this is what drives the badge/flag
// Reference "today" is fixed at 30 Jun 2025 to match the timeline and filters,
// so cards, badges and the DPO overdue list never disagree with the timeline.
const SLA_DAYS = 21;
const REFERENCE_TODAY = new Date(2025, 5, 30);

function deriveSlaFields(card: TicketCard): TicketCard {
  const match = card.submittedDate?.match(/(\d{2})\/(\d{2})\/(\d{4})/);
  if (!match) return card;
  const created = new Date(Number(match[3]), Number(match[2]) - 1, Number(match[1]));
  const ageDays = Math.floor((REFERENCE_TODAY.getTime() - created.getTime()) / 86400000);
  const remaining = SLA_DAYS - ageDays;

  if (remaining <= 0) {
    // There's no "Overdue Today" status — the SLA breach itself is already at
    // least 1 day overdue, so the minimum label is "Overdue by 1 Day".
    const overdueBy = -remaining + 1;
    return {
      ...card,
      isOverdue: true,
      daysType: 'overdue',
      daysLabel: `Overdue by ${overdueBy} Day${overdueBy === 1 ? '' : 's'}`,
    };
  }
  return {
    ...card,
    isOverdue: false,
    daysType: 'remaining',
    daysLabel: `${remaining} Day${remaining === 1 ? '' : 's'} Remaining`,
  };
}

